"""
pull_paper_values.py -- CPU only (numpy + json). Reads the cleaned repo layout and
  1) prints every number the paper still marks % CHECK, and saves them to paper_values.md
  2) writes the appendix tables as small .tex files that paper.tex pulls in with \\inputif{...}

USAGE (from the repo root, the PINN folder: electrochem/, heat_runs/, results/):
    python pull_paper_values.py
    python pull_paper_values.py --root . --out results/paper_figs

READS
    electrochem/results/results.json                                 electrochem results
    heat_runs/heat_results/results/*.json                   heat runs (plain weak, strong, band, starts)
    heat_runs/gm_heat_results/results/*.json                heat dual-norm runs (their *_start_* re-scores are skipped,
                                                           so each supervised start is counted once)
    electrochem/results/positive_control/*.json                     Da = 0 control
    run logs under electrochem/ and heat_runs/, val_refs.py                     run settings and the validation safety checks
WRITES (in --out)
    paper_values.md
    app_ec_perseed.tex  app_ec_extra.tex  app_heat_1d.tex  app_heat_2d.tex  app_heat_terms.tex  app_heat_band.tex
Copy the .tex files next to paper.tex. Anything missing is reported, never fatal.
"""
import os, re, json, glob, argparse
import numpy as np

SEEDS = (42, 43, 44)
TAGS = ("0.25/Fo", "1/Fo", "t=1")
HT = ["t=0.01", "t=0.05", "t=0.1", "t=0.3", "t=1.0"]
LOG, MISSING = [], []


def say(s=""):
    print(s); LOG.append(s)


def miss(s):
    MISSING.append(s); say(f"  [missing] {s}")


def g(x, p=3):
    if x is None or not np.isfinite(x):
        return "--"
    if abs(x) >= 10 ** p:                       # e.g. 984 -> 984, 3830 -> 3830
        return f"{x:.0f}"
    return f"{x:#.{p}g}".rstrip(".")


def cell(v, tex=False):
    v = [x for x in (v or []) if x is not None]
    if not v:
        return "--"
    a = np.asarray(v, float)
    if len(a) == 1:
        return f"{g(a[0])} ($n{{=}}1$)" if tex else f"{g(a[0])} (n=1)"
    s = f"{g(a.mean())} [{g(a.min())}--{g(a.max())}]" if tex else f"{g(a.mean())} [{g(a.min())}-{g(a.max())}]"
    return s.replace("[", "{\\scriptsize[").replace("]", "]}") if tex else s


def mean(v):
    v = [x for x in (v or []) if x is not None]
    return g(float(np.mean(v))) if v else "--"


def flat(d, pre=""):
    if isinstance(d, dict):
        for k, v in d.items():
            yield from flat(v, f"{pre}.{k}" if pre else str(k))
    elif isinstance(d, (int, float)) and not isinstance(d, bool):
        yield pre, d
    elif isinstance(d, list) and d and len(d) <= 10 and all(isinstance(x, (int, float)) for x in d):
        yield pre, d


def write_table(out, fname, label, caption, header, rows, colspec=None, size="\\scriptsize"):
    colspec = colspec or ("l" + "c" * (len(header) - 1))
    lines = ["% generated by pull_paper_values.py -- do not edit by hand", "\\begin{table}[H]", "\\centering",
             f"\\caption{{{caption}}}", f"\\label{{{label}}}", size, "\\setlength{\\tabcolsep}{4pt}",
             f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else " & ".join(r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    open(os.path.join(out, fname), "w").write("\n".join(lines))
    say(f"  wrote {fname} ({sum(r != 'MID' for r in rows)} rows)")


# ------------------------------------------------------------------------------------------------ loading
def load_json(p):
    try:
        return json.load(open(p))
    except Exception as e:
        miss(f"{p} ({e.__class__.__name__})"); return {}


def load_heat(root):
    rows = []
    # (folder under heat_runs, legacy tag, filename marker)
    for src, d, mark in (("heat_results", "heat_clash", "_clash_"), ("heat_results", "heat_compat", "_compat_"),
                         ("gm_heat_results", "gram_matrix_clash", "_clash_"), ("gm_heat_results", "gram_matrix_compat", "_compat_")):
        files = [f for f in sorted(glob.glob(os.path.join(root, "heat_runs", src, "results", "*.json")))
                 if mark in os.path.basename(f)]
        if not files:
            miss(f"heat_runs/{src}/results/*{mark}*.json")
        for f in files:
            if d.startswith("gram") and "_start_" in os.path.basename(f):
                continue                                  # duplicate re-score of a start; keep the original only
            r = load_json(f)
            if not r:
                continue
            r.setdefault("band", 0.0); r.setdefault("dual", False)
            r["band"] = float(r["band"] or 0.0); r["_dir"] = d
            rows.append(r)
    return rows


def hsel(H, **kw):
    return [r for r in H if all(r.get(k) == v for k, v in kw.items())]


def herr(rs, t):
    return [r.get("err", {}).get(t) for r in rs]


def hterm(rs, k):
    return [r.get("terms", {}).get(k) for r in rs]


# ------------------------------------------------------------------------------------------------ electrochem
def ec_early(R, arm):
    E = R.get("early_time_3seeds", {})
    return {s: E.get(f"{arm}_s{s}") for s in SEEDS}


def ec_summary(R, pat):
    return R.get("rework_summary", {}).get("test", {}).get(pat)


def ec_values(R, out):
    say("\n## Electrochem\n")
    if not R:
        miss("electrochem/results/results.json"); return
    say("results.json top-level keys: " + ", ".join(R.keys()))
    vc = R.get("rework_summary", {}).get("val_choice", {})
    say(f"validation choice: {json.dumps(vc)[:400]}")

    arms = [("warmstart", "Supervised start"), ("warm_weak", "Weak, IC on, warm"), ("cold_weak", "Weak, IC on, cold"),
            ("warm_weak_noIC", "Weak, IC off, warm"), ("cold_weak_noIC", "Weak, IC off, cold"),
            ("warm_strong", "Strong, IC on, warm"), ("warm_strong_noIC", "Strong, IC off, warm")]
    rows = []
    for a, lab in arms:
        per = ec_early(R, a)
        if not any(per.values()):
            miss(f"early_time_3seeds has no {a}"); continue
        for i, s in enumerate(SEEDS):
            v = per[s]
            rows.append([lab if i == 0 else "", str(s)] + [g(v[t]) if v else "--" for t in TAGS])
        rows.append("MID")
    if rows and rows[-1] == "MID":
        rows.pop()
    write_table(out, "app_ec_perseed.tex", "tab:app-ec-perseed",
                "Electrochemical problem, per seed: held-out relative $L^2$ error in $C$ at the three evaluation "
                "times (Figure~\\ref{fig:drift}).",
                ["Arm", "Seed", "$0.25/\\mathrm{Fo}$", "$1/\\mathrm{Fo}$", "$t=1$"], rows)

    # extra arms: ramp (strong and cold), mask (cold weak, warm strong)
    rows = []
    F = R.get("ramp_fix_3seeds", {})
    say("ramp_fix_3seeds keys: " + ", ".join(sorted(F.keys())[:40]))
    for tau in (0.01, 0.05):
        for arm, lab in (("warm_weak", "weak, warm"), ("cold_weak", "weak, cold"), ("warm_strong", "strong, warm")):
            ks = [f"ramp{tau:g}_{arm}_s{s}" for s in SEEDS if f"ramp{tau:g}_{arm}_s{s}" in F]
            if ks:
                rows.append([f"ramp $\\tau={tau:g}$, {lab}"] + [cell([F[k]["err"][t] for k in ks], tex=True) for t in TAGS])
    B = R.get("band_and_icweight_electrochem", {})
    say("band_and_icweight_electrochem keys: " + ", ".join(sorted(B.keys())[:40]))
    for b in (0.05, 0.1, 0.2):
        for arm, lab in (("warm_weak", "weak, warm"), ("cold_weak", "weak, cold"), ("warm_strong", "strong, warm")):
            k = f"band{b:g}_{arm}_s42"
            if k in B:
                rows.append([f"mask $b={b:g}$, {lab}"] + [cell([B[k]["err"][t]], tex=True) for t in TAGS])
    if rows:
        write_table(out, "app_ec_extra.tex", "tab:app-ec-extra",
                    "Electrochemical problem: ramped boundary and masked initial condition, all arms run. Mean "
                    "[min--max] over seeds; masked runs are seed 42 only.",
                    ["Variant", "$0.25/\\mathrm{Fo}$", "$1/\\mathrm{Fo}$", "$t=1$"], rows)
    else:
        miss("no ramp/mask arms found for app_ec_extra.tex")

    # penalty ablations from the earlier study, if they were logged under any key
    hits = [(k, v) for k, v in flat(R) if re.search(r"nosmooth|noends", k)]
    say("penalty-ablation entries in results.json: " + (str(hits[:12]) if hits else "none (paper uses the earlier logged values)"))


# ------------------------------------------------------------------------------------------------ heat
HEAT_ARMS = [("Weak, IC on", dict(form="weak", ic=1, dual=False)),
             ("Weak (dual), IC on", dict(form="weak", ic=1, dual=True)),
             ("Strong, IC on", dict(form="strong", ic=1, dual=False)),
             ("Weak, IC off", dict(form="weak", ic=0, dual=False)),
             ("Strong, IC off", dict(form="strong", ic=0, dual=False))]


def heat_values(H, out):
    say("\n## Heat\n")
    if not H:
        return
    say(f"{len(H)} heat runs loaded; example keys: {sorted(H[0].keys())}")

    # time tables, one per dimension
    for dim in (1, 2):
        rows = []
        for case in ("compat", "clash"):
            cname = "matching IC" if case == "compat" else "clashing IC"
            st = hsel(H, dim=dim, case=case, init="pre")
            if st:
                rows.append([f"{cname}: supervised start"] + [mean(herr(st, t)) for t in HT] + [cell(herr(st, "t=1.0"), tex=True)])
            for init in ("warm", "cold"):
                for lab, sel in HEAT_ARMS:
                    rs = hsel(H, dim=dim, case=case, init=init, band=0.0, **sel)
                    if rs:
                        rows.append([f"\\quad {init}, {lab}"] + [mean(herr(rs, t)) for t in HT] + [cell(herr(rs, "t=1.0"), tex=True)])
            rows.append("MID")
        if rows and rows[-1] == "MID":
            rows.pop()
        write_table(out, f"app_heat_{dim}d.tex", f"tab:app-heat-{dim}d",
                    f"Heat equation, {dim}D: relative error of the transient over time for every arm (mean over three "
                    "seeds; the last column repeats $t=1$ as mean [min--max]).",
                    ["Arm", "$0.01$", "$0.05$", "$0.1$", "$0.3$", "$1$", "$t=1$ range"], rows)

    # loss terms under the clash
    rows = []
    for dim in (1, 2):
        st = hsel(H, dim=dim, case="clash", init="pre")
        if st:
            rows.append([f"{dim}D, supervised start", cell(hterm(st, "ic"), True), cell(hterm(st, "strong"), True), cell(herr(st, "t=1.0"), True)])
        for init in ("warm", "cold"):
            for lab, sel in HEAT_ARMS[:3]:
                rs = hsel(H, dim=dim, case="clash", init=init, band=0.0, **sel)
                if rs:
                    rows.append([f"{dim}D, {init}, {lab}", cell(hterm(rs, "ic"), True), cell(hterm(rs, "strong"), True), cell(herr(rs, "t=1.0"), True)])
        rows.append("MID")
    if rows and rows[-1] == "MID":
        rows.pop()
    write_table(out, "app_heat_terms.tex", "tab:app-heat-terms",
                "Heat equation, clashing initial condition: initial-condition loss, pointwise PDE residual "
                "($12\\times$ mean squared strong residual on fixed points) and error at $t=1$, mean [min--max]. "
                "Dual-norm rows were scored on a different point set; read their residuals as orders of magnitude.",
                ["Arm", "IC loss", "pointwise residual", "error $t=1$"], rows)

    # masked IC
    rows = []
    for case in ("clash", "compat"):
        for b in (0.05, 0.1):
            for init in ("warm", "cold"):
                for form in ("weak", "strong"):
                    rs = hsel(H, dim=2, case=case, init=init, form=form, ic=1, band=b)
                    if rs:
                        rows.append([f"{case}, {init}, {form}, $b={b:g}$", cell(hterm(rs, "ic"), True),
                                     cell(herr(rs, "t=0.01"), True), cell(herr(rs, "t=1.0"), True)])
    if rows:
        write_table(out, "app_heat_band.tex", "tab:app-heat-band",
                    "Heat 2D, initial condition masked within a band $b$ of the boundary: IC loss and error, mean "
                    "[min--max] over three seeds.",
                    ["Arm", "IC loss", "error $t=0.01$", "error $t=1$"], rows)
    else:
        miss("no band runs found for app_heat_band.tex")

    # values the text quotes
    say("\n### Values quoted in the text (heat)")
    for dim in (1, 2):
        for init in ("warm", "cold"):
            rs = hsel(H, dim=dim, case="clash", init=init, form="weak", ic=1, dual=False, band=0.0)
            say(f"{dim}D clash {init} weak IC on: pointwise residual {cell(hterm(rs, 'strong'))}")
        st = hsel(H, dim=dim, case="clash", init="pre")
        say(f"{dim}D clash start (counted once, n={len(st)}): IC {cell(hterm(st, 'ic'))}, residual {cell(hterm(st, 'strong'))}")
        for lab, sel in (("start", dict(init="pre")), ("warm weak", dict(init="warm", form="weak", ic=1, dual=False, band=0.0)),
                         ("warm strong", dict(init="warm", form="strong", ic=1, dual=False, band=0.0))):
            rs = hsel(H, dim=dim, case="compat", **sel)
            say(f"{dim}D compat {lab}: error t=1 {cell(herr(rs, 't=1.0'))}")
        offs = [r["err"][t] for case in ("compat", "clash") for init in ("warm", "cold")
                for r in hsel(H, dim=dim, case=case, init=init, form="weak", ic=0, band=0.0) for t in HT]
        if offs:
            say(f"{dim}D weak IC off, all times and starts: min {g(min(offs))}, max {g(max(offs))}")

    say("\n### Gram-matrix entries (any key containing 'cond' or 'eig')")
    seen = set()
    for r in H:
        if r.get("dual"):
            for k, v in flat(r):
                if re.search(r"cond|eig", k, re.I) and (r.get("dim"), k) not in seen:
                    seen.add((r.get("dim"), k)); say(f"  {r.get('dim')}D {k}: {v}")
    if not seen:
        say("  none stored in the dual JSONs; keep the handoff values (about 7 in 2D, 4 in 1D) or recompute")


# ------------------------------------------------------------------------------------------------ other checks
def other_checks(root):
    say("\n## Positive control (Da = 0)\n")
    for f in sorted(glob.glob(os.path.join(root, "electrochem", "results", "positive_control", "*.json"))):
        say(f"### {os.path.basename(f)}")
        for k, v in list(flat(load_json(f)))[:60]:
            say(f"  {k}: {v}")

    say("\n## Run settings from logs\n")
    pat = re.compile(r"batch|bs[ =:]|epoch|step|lr[ =:]|phase|split|w_ic|icw|W_IC|device|cuda|A100|T4|H100|L4|GPU", re.I)
    for rel in ("electrochem/results/logs/warmstart_s43.log", "electrochem/results/logs/warm_weak_s43.log", "electrochem/results/logs/warm_strong_s43.log",
                "electrochem/results/logs/icw0.1_warm_weak_s43.log", "heat_runs/heat_results/logs/d2_clash_warm_weak_ic1_s42.log",
                "heat_runs/gm_heat_results/logs/d2_clash_warm_weak_ic1_dual_s42.log"):
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            miss(rel); continue
        say(f"### {rel}")
        hits = [ln.rstrip() for ln in open(p, errors="replace").readlines()[:400] if pat.search(ln)]
        for ln in hits[:15]:
            say("  " + ln[:200])

    say("\n## Validation-reference safety checks (val_refs.py)\n")
    p = os.path.join(root, "val_refs.py")
    if os.path.exists(p):
        for i, ln in enumerate(open(p, errors="replace"), 1):
            if re.search(r"check|assert|safety|verify|max\s*\|", ln, re.I):
                say(f"  {i}: {ln.rstrip()[:160]}")
    else:
        miss("val_refs.py")


# ------------------------------------------------------------------------------------------------ main
if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--out", default=os.path.join("results", "paper_figs"))
    a = ap.parse_args()
    out = a.out if os.path.isabs(a.out) else os.path.join(a.root, a.out)
    os.makedirs(out, exist_ok=True)
    say("# Paper values (generated by pull_paper_values.py)")
    R = load_json(os.path.join(a.root, "electrochem", "results", "results.json"))
    H = load_heat(a.root)
    ec_values(R, out)
    heat_values(H, out)
    other_checks(a.root)
    if MISSING:
        say(f"\n{len(MISSING)} items missing (listed above); everything else was written.")
    open(os.path.join(out, "paper_values.md"), "w").write("\n".join(LOG) + "\n")
    print(f"\nsaved {os.path.join(out, 'paper_values.md')}")